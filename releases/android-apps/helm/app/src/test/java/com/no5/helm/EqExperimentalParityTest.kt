/** Captures production UI only. Frozen EXP1 references are never generated by this test. */
@RunWith(RobolectricTestRunner::class)
@Config(sdk=[35],qualifiers="de-w1000dp-h600dp-land-xhdpi")
@GraphicsMode(GraphicsMode.Mode.NATIVE)
class EqExperimentalParityTest {
 @get:Rule val ui=createComposeRule()
 private class Port(model:SoundPreset):AudioSoundPort{
  override val state=MutableSourceFeed(soundFixture().copy(preset=model,headroomDb=model.reserveDb,capabilities=SoundCapabilities(true,true,true,true,eqProjection=true,experimentalEq=true),eqEditing=SoundEqEditing()))
  override val spectrum=MutableSourceFeed<AudioSpectrumFrame?>(null);override val results=MutableSourceFeed<AudioSoundResult?>(null)
  var command:AudioSoundCommand.Preview?=null;var id=0L
  override fun submit(command:AudioSoundCommand):Long{this.command=command as? AudioSoundCommand.Preview;return ++id}
  override fun setEditorVisible(visible:Boolean,eqVisible:Boolean){};override fun refresh(){};override fun close(){}
  fun applied(constrained:Boolean=false){val c=command!!;val m=c.preset!!;val exp=c.eqEditing?.experimental==true
   val normal=if(exp)m.copy(eqPoints=m.eqPoints.map{it.copy(gainDb=minOf(it.gainDb,m.reserveDb))})else null
   state.emit(state.value.copy(preset=m,preview=SoundPreview(c.previewId,9999999999999,true,false),eqEditing=SoundEqEditing(exp,constrained,normal)))
   results.emit(AudioSoundResult(id,"APPLIED"))
  }
 }
 @Test fun captureApprovedProductionStates(){
  val context=RuntimeEnvironment.getApplication();val original=com.no5.ui.UiLanguage.current(context)
  val lang=mutableStateOf("de");val night=mutableStateOf(false);val font=mutableStateOf(1f)
  val model=SoundPreset("stereo","EQ · EXP1","stereo_4_1",listOf(SoundEqPoint("low",80.0,3.0,2.0),SoundEqPoint("mid",1000.0,4.0,2.0),SoundEqPoint("high",9000.0,2.0,2.0)),eqEnabled=true,reserveDb=6.0)
  fun controller(s:String):AudioNativeController{
   val m=if(s=="high")model.copy(reserveDb=18.0,eqPoints=model.eqPoints.map{if(it.id=="mid")it.copy(gainDb=20.5)else it})else model
   val p=Port(m);val source=object:AudioSourcePort by MockAudioSource(now={10000}){override val sound=p}
   val a=AudioNativeController(Dispatchers.Unconfined,{10000},false,false,source,eqValidator=FixtureEqValidator,eqValidationDispatcher=Dispatchers.Unconfined)
   a.openSoundEditor(false);val c=a.soundEditor;c.choosePoint("mid")
   if(s=="normal"){c.updatePoint(m.eqPoints[1]);p.applied()}else{c.useExperimental(true);p.applied(s=="limit");if(s=="ending")c.useExperimental(false)}
   return a
  }
  context.getSharedPreferences("no5-sound-drafts-v1",0).edit().clear().commit()
  val active=mutableStateOf(controller("normal"))
  ui.setContent{
   com.no5.ui.UiLanguage.acceptConfirmed(context,lang.value)
   CompositionLocalProvider(LocalDensity provides Density(2f,font.value)){
    MaterialTheme{Box(Modifier.size(1000.dp,600.dp)){
     Canvas(Modifier.size(1000.dp,600.dp)){HelmScene(context,night.value).drawChrome(drawContext.canvas.nativeCanvas,"AUDIO",renderValues(HelmState.unavailable()),"EXP1 · PROPOSAL")}
     AudioScreen(.5f,night.value,active.value)
     Canvas(Modifier.size(1000.dp,600.dp)){KnobOverlay(context).draw(drawContext.canvas.nativeCanvas,night.value,active.value,useSelectedAudioFader=true)}
    }}
   }
  }
  try{
   for(l in listOf("de","en","af"))for(dark in listOf(false,true))for(f in listOf(1f,1.25f))for(s in listOf("normal","test","limit","high","ending")){
    ui.runOnIdle{active.value.dispose();context.getSharedPreferences("no5-sound-drafts-v1",0).edit().clear().commit();active.value=controller(s);lang.value=l;night.value=dark;font.value=f};ui.waitForIdle()
    ui.runOnUiThread{
     val view=(ui as androidx.compose.ui.test.junit4.AndroidComposeTestRule<*,*>).activity.window.decorView
     val b=Bitmap.createBitmap(view.width,view.height,Bitmap.Config.ARGB_8888);view.draw(android.graphics.Canvas(b))
     val dir=java.io.File(System.getProperty("no5.renderOutputDir"),"eq-experimental-production").apply{mkdirs()}
     java.io.File(dir,"$l-${if(dark)"night"else"day"}-font$f-$s.png").outputStream().use{b.compress(Bitmap.CompressFormat.PNG,100,it)};b.recycle()
    }
   }
  }finally{ui.runOnIdle{active.value.dispose();context.getSharedPreferences("no5-sound-drafts-v1",0).edit().clear().commit();com.no5.ui.UiLanguage.acceptConfirmed(context,original)}}
 }
}
